function initialLanguage(): AppLanguage {
  try {
    const stored = window.localStorage.getItem(LANGUAGE_KEY)
    if (stored === "ko" || stored === "en") return stored
  } catch {
    // Storage can be unavailable in a privacy-restricted browser.
  }
  return navigator.language.toLowerCase().startsWith("ko") ? "ko" : "en"
}

void i18n.use(initReactI18next).init({
  resources: {
    ko: { translation: ko, codes: {} },
    en: { translation: en, codes: codeLabels },
  },
  lng: initialLanguage(),
  fallbackLng: "ko",
  supportedLngs: LANGUAGES,
  ns: ["translation", "codes"],
  defaultNS: "translation",
  interpolation: { escapeValue: false },
  initAsync: false,
})

function applyLanguage(language: string) {
  const normalized: AppLanguage = language.startsWith("en") ? "en" : "ko"
  document.documentElement.lang = normalized
  try {
    window.localStorage.setItem(LANGUAGE_KEY, normalized)
  } catch {
    // Language still works for this session when storage is unavailable.
  }
}

applyLanguage(i18n.resolvedLanguage ?? i18n.language)
i18n.on("languageChanged", applyLanguage)

export function language(): AppLanguage {
  return (i18n.resolvedLanguage ?? i18n.language).startsWith("en") ? "en" : "ko"
}

export function tr(key: string, options?: TOptions): string {
  return String(i18n.t(key, options))
}

